export function translate(language: Language, key: string): string {
  return messages[language][key] ?? messages.ru[key] ?? key;
}

export function localizedError(language: Language, error: unknown, fallbackKey: string): string {
  const message = error instanceof Error ? error.message.trim() : typeof error === "string" ? error.trim() : "";
  if (!message) return translate(language, fallbackKey);
  if (Object.values(messages[language]).includes(message)) return message;
  if (language === "ru") return message;
  const knownRussianMessage = Object.entries(messages.ru).find(
    ([, russianMessage]) =>
      russianMessage.length > 12 &&
      (message === russianMessage || message.startsWith(`${russianMessage}:`)),
  );
  if (knownRussianMessage) {
    const [key, russianMessage] = knownRussianMessage;
    const translatedMessage = messages[language][key] ?? translate(language, fallbackKey);
    const technicalDetails = message.slice(russianMessage.length);
    return /\p{Script=Cyrillic}/u.test(technicalDetails)
      ? translatedMessage
      : `${translatedMessage}${technicalDetails}`;
  }
  if (language === "en" && !/\p{Script=Cyrillic}/u.test(message)) return message;
  return translate(language, fallbackKey);
}

